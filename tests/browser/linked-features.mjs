// Called by the Go acceptance harness against its isolated real server.
import assert from 'node:assert/strict';
import {tmpdir} from 'node:os';
import {join} from 'node:path';
import {checkAnnouncementRecovery} from './announcement-recovery.mjs';
const {chromium} = await import(process.env.PLAYWRIGHT_MODULE || 'playwright');
const base = process.env.CONWAY_TEST_BASE_URL, plan = process.env.CONWAY_TEST_PLAN_ID;
if (!base || !plan) throw new Error('Run the linked features browser Go acceptance harness.');
const channel = process.env.PLAYWRIGHT_BROWSER_CHANNEL;
const browser = await chromium.launch({headless:true,...(channel ? {channel} : {})});
const page = await browser.newPage({viewport:{width:1280,height:960}});
const errors = []; page.on('pageerror',error=>errors.push(error.message));
const api = (path, options={}) => page.evaluate(async ({path,options}) => {
  const result = await fetch(path,{...options,headers:{'Content-Type':'application/json',Authorization:'Bearer '+localStorage.getItem('conway_token')}});
  const text=await result.text(); if(!result.ok) throw new Error(result.status+' '+text); return JSON.parse(text);
},{path,options});
const overlay=page.locator('#linked-sheets-overlay');
try {
  await page.goto(base+'?view=plan&plan='+plan);
  await page.locator('#login-user').fill(process.env.CONWAY_TEST_USERNAME);
  await page.locator('#login-pass').fill(process.env.CONWAY_TEST_PASSWORD);
  await page.locator('#signin-form button[type=submit]').click();
  const announcements=page.locator('#announcements-overlay');
  await announcements.waitFor({state:'visible'});
  assert.equal(await announcements.locator('[data-announcement-action]').count(),3);
  await page.waitForFunction(async()=>{const r=await fetch('/api/announcements',{headers:{Authorization:'Bearer '+localStorage.getItem('conway_token')}});return r.ok&&(await r.json()).features.every(f=>f.announced);});
  assert.equal((await api('/api/announcements')).features.some(f=>f.visited),false);
  await page.keyboard.press('Escape'); await announcements.waitFor({state:'hidden'});
  await page.reload(); await page.locator('#plan-linked-sheets').waitFor();
  assert.equal(await announcements.isVisible(),false,'automatic introduction must not recur');
  assert.ok(await page.locator('#plan-linked-sheets [data-announcement-indicator]').count());
  await page.locator('#help-btn').click(); await page.locator('#whats-new-btn').click();
  await announcements.waitFor({state:'visible'}); assert.equal(await announcements.locator('[data-announcement-action]').count(),3);
  await page.setViewportSize({width:360,height:800});
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false);
  await page.screenshot({path:join(process.env.CONWAY_TEST_ARTIFACT_DIR||tmpdir(),'conway-announcements-mobile.png'),fullPage:true});
  await page.setViewportSize({width:1280,height:960});
  await announcements.locator('[data-announcement-close]').click(); await announcements.waitFor({state:'hidden'});
  await page.locator('#plan-linked-sheets').click(); await overlay.locator('[data-link]').waitFor();
  await page.waitForFunction(async()=>{const r=await fetch('/api/announcements',{headers:{Authorization:'Bearer '+localStorage.getItem('conway_token')}});return (await r.json()).features.find(f=>f.id==='linked-sheet-import-v1')?.visited;});
  const form=overlay.locator('[data-link]');
  await form.locator('[name=spreadsheetUrl]').fill('https://docs.google.com/spreadsheets/d/generic-sheet-id/edit');
  await form.locator('[name=range]').fill('Teams!A1:B20'); await form.locator('button[type=submit]').click();
  await overlay.locator('[data-source]').waitFor();
  const sources=await api('/api/plan/'+plan+'/sources'), sid=sources.sources[0].id;
  assert.equal(sources.sources[0].mode,'review');
  const tracks=async()=> (await api('/api/plan/'+plan)).teams.find(t=>t.name==='Team A').tracks;
  assert.equal(await tracks(),2,'linking in review mode must leave the plan unchanged');
  await overlay.locator('[data-history]').click(); await overlay.locator('[data-version]').first().waitFor();
  const first=await overlay.locator('[data-version]').first().getAttribute('data-version');
  await overlay.locator('[data-version]').first().click(); await overlay.locator('[data-apply]').click();
  await overlay.locator('[data-source]').waitFor(); assert.equal(await tracks(),3);
  await overlay.locator('[data-check]').click(); await page.waitForFunction(async({plan,sid})=>{const r=await fetch('/api/plan/'+plan+'/sources/'+sid+'/versions',{headers:{Authorization:'Bearer '+localStorage.getItem('conway_token')}});return (await r.json()).versions.length===2;},{plan,sid});
  await overlay.locator('[data-history]').click(); await overlay.locator('[data-version]').first().waitFor();
  const versions=(await api('/api/plan/'+plan+'/sources/'+sid+'/versions')).versions;
  const next=versions.find(v=>v.id!==first).id;
  await overlay.locator(`[data-version="${next}"]`).click(); await overlay.locator('[data-apply]').waitFor();
  await api('/api/plan/'+plan+'/teams',{method:'PATCH',body:JSON.stringify({name:'Team A',tracks:6})});
  await overlay.locator('[data-apply]').click(); await overlay.locator('[data-sheet-status][role=alert]').waitFor();
  assert.match(await overlay.locator('[data-sheet-status]').textContent(),/changed|review/i); assert.equal(await tracks(),6);
  await overlay.locator('[data-back]').click(); await overlay.locator(`[data-version="${next}"]`).click();
  await overlay.locator('[data-apply]').click(); await overlay.locator('[data-source]').waitFor(); assert.equal(await tracks(),4);
  await overlay.locator('[data-history]').click(); await overlay.locator(`[data-version="${first}"]`).click();
  assert.match(await overlay.locator('[data-apply]').textContent(),/Restore/); await overlay.locator('[data-apply]').click();
  await overlay.locator('[data-source]').waitFor(); assert.equal(await tracks(),3);
  assert.equal((await api('/api/plan/'+plan+'/sources/'+sid+'/versions')).versions.length,2);
  await page.setViewportSize({width:360,height:800});
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false);
  await page.screenshot({path:join(process.env.CONWAY_TEST_ARTIFACT_DIR||tmpdir(),'conway-linked-sources-mobile.png'),fullPage:true});
  await overlay.locator('[data-close]').click(); await overlay.waitFor({state:'hidden'});
  await page.setViewportSize({width:1280,height:960});
  await page.goto(base+'?view=home');await page.locator('#help-btn').waitFor();
  await page.locator('#help-btn').click();await page.locator('#whats-new-btn').click();
  await announcements.waitFor({state:'visible'});
  await announcements.locator('[data-announcement-action="linked-sheet-import-v1"]').click();
  await page.locator('[data-pending-destination]').waitFor();
  assert.match(await page.locator('[data-pending-destination]').textContent(),/Choose a plan.*Linked Google Sheets/);
  await page.locator('[data-cancel-destination]').waitFor({state:'visible'});
  await page.locator(`.plan-open[data-id="${plan}"]`).click();
  await overlay.locator('[data-source]').waitFor({state:'visible'});
  assert.equal(await page.locator('[data-pending-destination]').count(),0);
  await overlay.locator('[data-close]').click();await overlay.waitFor({state:'hidden'});
  assert.deepEqual(errors,[]);
  await checkAnnouncementRecovery(browser,base);
  console.log(JSON.stringify({announcedOnce:true,replay:true,visitedAfterOpen:true,reviewApply:true,staleConflict:true,restore:true,immutableCaptureCount:2,mobileOverflow:false,pageErrors:errors}));
} catch(error) {
  await page.screenshot({path:join(process.env.CONWAY_TEST_ARTIFACT_DIR||tmpdir(),'conway-linked-features-failure.png'),fullPage:true});
  console.error(await page.locator('body').innerText()); throw error;
} finally { await browser.close(); }
